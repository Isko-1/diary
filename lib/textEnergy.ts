/**
 * Энергия текста (ось arousal) по лексике и пунктуации, без LLM.
 * Отдельно от настроения (valence): «Концерт! Прыгали и орали всю ночь» — это высокая энергия,
 * «долго гуляли, пили какао» — низкая, «срочно, дедлайн» — высокая и напряжённая.
 * Возвращает 0..1 и список сработавших признаков для объяснения.
 */
const L = "(?<![а-яёa-z])";
const E = "(?![а-яё])";
const re = (s: string) => new RegExp(s);

// Движение, шум, яркость, события
const HIGH: [RegExp, string][] = [
  [re(`${L}прыга|${L}прыжк|${L}подпрыг`), "прыгали"],
  [re(`${L}орал[аи]?${E}|${L}орут|${L}кричал|${L}крик`), "кричали"],
  [re(`${L}танц|${L}пляс`), "танцы"],
  [re(`${L}бега|${L}бежал|${L}мчал|${L}гонк|${L}спринт|${L}пробежк`), "бег"],
  [re(`${L}громк`), "громко"],
  [re(`${L}ярк`), "ярко"],
  [re(`${L}шумн|${L}шум${E}`), "шум"],
  [re(`${L}драйв|${L}адреналин|${L}взрыв`), "драйв"],
  [re(`${L}безум|${L}бешен|${L}сумасшед|${L}неистов`), "безумие"],
  [re(`${L}зажигал|${L}отрывал`), "зажигали"],
  [re(`${L}концерт|${L}фестивал|${L}вечеринк|${L}тусовк|${L}клуб`), "событие"],
  [re(`${L}толп`), "толпа"],
  [re(`${L}быстр|${L}скорост`), "скорость"],
  [re(`${L}трениров|${L}футбол|${L}баскетбол|${L}соревнован|${L}матч`), "спорт"],
  [re(`${L}хохот|${L}хохотал|${L}ржал|${L}веселил`), "веселье"],
];

// Срочность и тревога: сильный признак напряжения
const TENSION = re(`${L}дедлайн|${L}срочн|${L}аврал|${L}спешил|${L}суета|${L}сдач(?:а|и|е|у|ей)${E}`);

// Покой, неспешность, тишина, уют
const LOW: [RegExp, string][] = [
  [re(`${L}тишин|${L}тих(?:о|ий|ая|ое|ие)${E}`), "тишина"],
  [re(`${L}спокой`), "спокойно"],
  [re(`${L}медленн|${L}неспешн|${L}не спеша|${L}ленив|${L}неторопл`), "неспешно"],
  [re(`${L}дремал|${L}лежал|${L}валял|${L}плед`), "покой"],
  [re(`${L}уютн|${L}умиротвор|${L}расслаб|${L}безмятеж`), "уют"],
  [re(`${L}одинок|${L}груст|${L}тоск|${L}печал|${L}устал`), "грусть"],
  [re(`${L}молча|${L}помолч`), "молчание"],
  [re(`${L}долго`), "долго"],
  [re(`${L}гуля|${L}прогул`), "прогулка"],
  [re(`${L}морос|${L}дождь за окном`), "дождь за окном"],
];

export function textEnergy(text: string): { energy: number; hits: string[] } {
  const t = text.toLowerCase();
  const hits: string[] = [];

  let high = 0;
  for (const [r, name] of HIGH) if (r.test(t)) { high++; hits.push(`+${name}`); }
  let low = 0;
  for (const [r, name] of LOW) if (r.test(t)) { low++; hits.push(`−${name}`); }

  const excl = (text.match(/!/g) ?? []).length;
  const caps = (text.match(/(?<![А-ЯЁA-Z])[А-ЯЁA-Z]{3,}(?![А-ЯЁA-Z])/g) ?? []).length;
  const tension = TENSION.test(t);

  let e = 0.5;
  e += Math.min(0.4, high * 0.11);
  e -= Math.min(0.36, low * 0.12);
  e += Math.min(0.15, excl * 0.05);
  e += Math.min(0.09, caps * 0.03);
  if (tension) { e += 0.3; hits.push("+срочность"); }
  if (excl) hits.push(`+восклицания×${excl}`);

  return { energy: Math.min(0.97, Math.max(0.05, e)), hits };
}
